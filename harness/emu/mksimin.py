# DB=$00 variant of the stage-1 loop, followed only by DATA_SND, then SOUND, then JUMP to a stub.
import mkscript
P=lambda *b: ('pkt',bytes(b)); W=lambda n: ('wait',n); X=lambda i: ('xfer',i)
def dsnd(addr,data):
    out=[]
    for i in range(0,len(data),11):
        ch=data[i:i+11]; a=addr+i
        out+=[P(0x79,a&0xff,(a>>8)&0xff,a>>16,len(ch),*ch),W(2)]
    return out
stage1=bytes([0x4b,0xab, 0x9c,0x00,0x17, 0x9c,0x00,0x42, 0xad,0xdb,0xff, 0xf0,0x05, 0x20,0xed,0xbb, 0x80,0xf3, 0x20,0xf0,0xbb, 0x80,0xee])
stage2=bytes([0xa9,0x5a, 0x8f,0x80,0x1a,0x7e, 0x80,0xfe])
s=[W(255),W(45)]+dsnd(0x7e1800,stage1)+[P(0x91,0x00,0x18,0x00,0,0,0),W(10)]
s+=dsnd(0x7e1900,stage2)+dsnd(0x7fe000,bytes(range(44)))
s+=[P(0x91,0x00,0x19,0x00,0,0,0),W(60)]
mkscript.build('simin.gb',s,[])
