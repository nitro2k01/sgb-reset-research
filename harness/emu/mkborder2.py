import subprocess,sys
def payload_set(n):   # in-menu style: set border n via $DEA6 (for making the border non-default first)
    body=bytes([0x08,0xE2,0x30, 0xA9,0x60,0x8D,0x18,0x08, 0xA9,n,0x8D,0x03,0x0C,
                0x22,0x2B,0xD5,0x01, 0x20,0xA6,0xDE, 0x22,0x2B,0xD5,0x01, 0x28])
    return bytes([0xC9,0x04,0xD0,len(body)])+body+bytes([0x60])
def payload_reset():  # forget custom border, restart main-loop init at $CE00
    body=bytes([0xE2,0x30, 0xA9,0x60,0x8D,0x18,0x08,
                0x9C,0x0C,0x0F, 0x9C,0x4B,0x0F, 0x9C,0x4C,0x0F,
                0x68,0x68, 0x4C,0x00,0xCE])
    return bytes([0xC9,0x04,0xD0,len(body)])+body+bytes([0x60])
def payload_stock():
    body=bytes([0x08,0xE2,0x30,
      0xA9,0x60,0x8D,0x18,0x08,            # disarm hook: $0818 = RTS
      0xA9,0x01,0x8D,0x03,0x0C,            # $0C03 = 1 (stock SGB border)
      0x8D,0x47,0x0C,                      # $0C47 = 1 (border currently shown)
      0x9C,0x0C,0x0F, 0x9C,0x4B,0x0F, 0x9C,0x4C,0x0F,   # forget custom border
      0xA9,0xE8,0x8F,0x01,0xC0,0x7E,
      0x22,0x2B,0xD5,0x01, 0x22,0x46,0xD5,0x01,
      0xC2,0x20,0xA9,0x00,0x82,0x85,0xC0,0xE2,0x20,0xA9,0x02,0x85,0xC2,
      0x22,0xD8,0xFE,0x00,                 # fade out
      0x22,0x7B,0xF8,0x00, 0x22,0x27,0xDC,0x01, 0x22,0xFD,0xF8,0x00, 0x22,0x7B,0xF8,0x00,
      0xA9,0x01,0x8D,0x48,0x0C,
      0x22,0x68,0x80,0x01,                 # load border number $0C03
      0xC2,0x20,0xA9,0x10,0x82,0x85,0xC0,0xE2,0x20,0xA9,0x02,0x85,0xC2,
      0x22,0xDC,0xFE,0x00,                 # fade in
      0x28])
    return bytes([0xC9,0x04,0xD0,len(body)])+body+bytes([0x60])
def datasnd(addr,bank,data,wait):
    out=[]
    for i in range(0,len(data),11):
        ch=data[i:i+11]; a=addr+i
        out.append(f'{wait if i==0 else 4}:'+bytes([0x79,a&0xff,a>>8,bank,len(ch)]).hex()+ch.hex())
    return out
mode=sys.argv[1]
pk=[]
if mode in ('both','set'):
    pk+=datasnd(0x1A00,0,payload_set(int(sys.argv[2]) if len(sys.argv)>2 else 5),200)
    pk+=datasnd(0x0818,0,bytes([0x4C,0x00,0x1A]),4)
if mode in ('custom',):
    pk+=datasnd(0x0F0C,0,bytes([1]),200)
    pk+=datasnd(0x0F04,0,bytes([1]),4)
    pk+=datasnd(0x0F4C,0,bytes([1]),4)
    pk+=datasnd(0x1A00,0,payload_stock(),150)
    pk+=datasnd(0x0818,0,bytes([0x4C,0x00,0x1A]),4)
if mode in ('both','reset'):
    pk+=datasnd(0x1A00,0,payload_reset(),200)
    pk+=datasnd(0x0818,0,bytes([0x4C,0x00,0x1A]),4)
subprocess.run(['python3','-I','mkgb.py','border.gb','03','33','1']+pk,check=True)
print(len(payload_reset()))
