import sys
# mkboot2.py out.bin cart.gb gap_iters tail_frames   (gap loop: 7 M-cycles/iter)
out,cartf,gap,tail=sys.argv[1],sys.argv[2],int(sys.argv[3]),int(sys.argv[4])
cart=open(cartf,'rb').read()
pk=[]
for k,cmd in enumerate([0xf1,0xf3,0xf5,0xf7,0xf9,0xfb]):
    n=14 if k<5 else 6; d=cart[0x104+14*k:0x104+14*k+n]
    pk.append(bytes(bytes([cmd,sum(d)&0xff])+d).ljust(16,b'\0'))
code=bytearray()
def e(*b): code.extend(b)
def rel(t): return (t-(len(code)+2))&0xff
e(0x31,0xfe,0xff, 0x3e,0x91,0xe0,0x40, 0x21,0,0); fx=len(code)-2
e(0x0e,6)
loop=len(code)
e(0xc5, 0xaf,0xe0,0x00,0x3e,0x30,0xe0,0x00,0x06,0x10)
byte=len(code); e(0x1e,0x08,0x2a,0x57)
bit=len(code); e(0xcb,0x42,0x3e,0x10,0x20,0x02,0x3e,0x20,0xe0,0x00,0x3e,0x30,0xe0,0x00,0xcb,0x1a,0x1d); e(0x20,rel(bit))
e(0x05); e(0x20,rel(byte))
e(0x3e,0x20,0xe0,0x00,0x3e,0x30,0xe0,0x00)
e(0xc1,0x0d)
e(0x28,0)                          # jr z,done (fixup) -- no gap after last packet
jz=len(code)-1
if gap>0:
    e(0x11,gap&0xff,gap>>8); g=len(code); e(0x1b,0x7a,0xb3); e(0x20,rel(g))
e(0x18,rel(loop))
code[jz]=(len(code)-(jz+1))&0xff
# tail: wait N frames like stock ($00C2 style)
if tail>0:
    e(0x16,tail); w=len(code); e(0xf0,0x44,0xfe,0x90,0x20,0xfa,0x1e,0x00,0x1d,0x20,0xfd,0x15); e(0x20,rel(w))
e(0xc3,0xfc,0x00)
p0=len(code); code[fx]=p0&0xff; code[fx+1]=p0>>8
for p in pk: code.extend(p)
assert len(code)<=0xfc
rom=bytearray(256); rom[:len(code)]=code; rom[0xfc:]=bytes([0x3e,0x01,0xe0,0x50])
open(out,'wb').write(rom)
